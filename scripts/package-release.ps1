[CmdletBinding()]
param()

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$release = Join-Path $root "release"
$staging = Join-Path $release "staging"
$zip = Join-Path $release "RoadRushLAN-Share.zip"
$marker = Join-Path $release ".roadrush-staging-generated"
$dist = Join-Path $root "dist"
$serverBundle = Join-Path $root "server\server.bundle.mjs"
$startScript = Join-Path $root "Start-LAN-Server.ps1"
$serverReadme = Join-Path $root "docs\SERVER-README.md"
$combinedReadme = Join-Path $root "docs\README.txt"

function Assert-Path($condition, $message) {
    if (-not $condition) { throw $message }
}

function Free-Port {
    $listener = New-Object System.Net.Sockets.TcpListener([System.Net.IPAddress]::Loopback, 0)
    $listener.Start()
    try {
        return ([System.Net.IPEndPoint]$listener.LocalEndpoint).Port
    } finally {
        $listener.Stop()
    }
}

Set-Location -LiteralPath $root

Write-Host "RoadRush LAN release packaging"
Write-Host "Root: $root"
Write-Host ""

$npm = Get-Command npm.cmd -ErrorAction SilentlyContinue
if (-not $npm) { $npm = Get-Command npm -ErrorAction SilentlyContinue }
Assert-Path $npm "npm was not found on PATH."
$node = Get-Command node -ErrorAction SilentlyContinue
Assert-Path $node "Node.js was not found on PATH."

Write-Host "[1/6] Building production extension and server bundle..."
& $npm.Source run build
Assert-Path ($LASTEXITCODE -eq 0) "Extension build failed."
& $npm.Source run build:server
Assert-Path ($LASTEXITCODE -eq 0) "Server bundle build failed."

Assert-Path (Test-Path -LiteralPath (Join-Path $dist "manifest.json")) "dist\manifest.json is missing."
Assert-Path (Test-Path -LiteralPath (Join-Path $dist "game.html")) "dist\game.html is missing."
Assert-Path (Test-Path -LiteralPath $serverBundle) "server\server.bundle.mjs is missing."
Assert-Path (Test-Path -LiteralPath $startScript) "Start-LAN-Server.ps1 is missing."
Assert-Path (Test-Path -LiteralPath $serverReadme) "docs\SERVER-README.md is missing."
Assert-Path (Test-Path -LiteralPath $combinedReadme) "docs\README.txt is missing."

$manifest = Get-Content -LiteralPath (Join-Path $dist "manifest.json") -Raw -Encoding UTF8 | ConvertFrom-Json
Assert-Path ($manifest.manifest_version -eq 3) "dist manifest is not Manifest V3."
Assert-Path ($manifest.action.default_popup -eq "popup.html") "Unexpected extension popup entry."
foreach ($file in @("popup.html", "game.html", "launcher.html", "icons\icon16.png", "icons\icon32.png", "icons\icon48.png", "icons\icon128.png")) {
    Assert-Path (Test-Path -LiteralPath (Join-Path $dist $file)) "Required extension file is missing: $file"
}

New-Item -ItemType Directory -Path $release -Force | Out-Null
if (Test-Path -LiteralPath $staging) {
    Assert-Path (Test-Path -LiteralPath $marker) "Refusing to remove release\staging because it was not created by this packaging script."
    Remove-Item -LiteralPath $staging -Recurse -Force
}
if (Test-Path -LiteralPath $zip) { Remove-Item -LiteralPath $zip -Force }
Set-Content -LiteralPath $marker -Value "Generated by scripts\package-release.ps1" -Encoding ASCII
New-Item -ItemType Directory -Path $staging | Out-Null

Write-Host "[2/6] Copying allowlisted extension files..."
$extensionOut = Join-Path $staging "ChromeExtension"
New-Item -ItemType Directory -Path $extensionOut | Out-Null
foreach ($file in @("manifest.json", "game.html", "launcher.html", "popup.html")) {
    Copy-Item -LiteralPath (Join-Path $dist $file) -Destination (Join-Path $extensionOut $file)
}
foreach ($dir in @("assets", "icons")) {
    Copy-Item -LiteralPath (Join-Path $dist $dir) -Destination (Join-Path $extensionOut $dir) -Recurse
}

Write-Host "[3/6] Copying LAN server and web build..."
$lanOut = Join-Path $staging "LANServer"
New-Item -ItemType Directory -Path $lanOut | Out-Null
Copy-Item -LiteralPath $serverBundle -Destination (Join-Path $lanOut "server.bundle.mjs")
Copy-Item -LiteralPath $startScript -Destination (Join-Path $lanOut "Start-LAN-Server.ps1")
Copy-Item -LiteralPath $serverReadme -Destination (Join-Path $lanOut "README.md")
$webOut = Join-Path $lanOut "web"
New-Item -ItemType Directory -Path $webOut | Out-Null
Copy-Item -Path (Join-Path $dist "*") -Destination $webOut -Recurse
Copy-Item -LiteralPath $combinedReadme -Destination (Join-Path $staging "README.txt")

Write-Host "[4/6] Verifying staging layout..."
foreach ($file in @(
    "ChromeExtension\manifest.json",
    "ChromeExtension\game.html",
    "ChromeExtension\popup.html",
    "ChromeExtension\launcher.html",
    "ChromeExtension\icons\icon128.png",
    "LANServer\server.bundle.mjs",
    "LANServer\Start-LAN-Server.ps1",
    "LANServer\README.md",
    "LANServer\web\game.html",
    "LANServer\web\assets",
    "README.txt"
)) {
    Assert-Path (Test-Path -LiteralPath (Join-Path $staging $file)) "Staging is missing: $file"
}
$badFiles = Get-ChildItem -LiteralPath $staging -Recurse -File | Where-Object {
    $_.Name -match '\.(sqlite|sqlite-wal|sqlite-shm|log|env)$' -or $_.FullName -match '\\node_modules\\'
}
Assert-Path (-not $badFiles) "Staging contains a forbidden file: $($badFiles | Select-Object -First 1 -ExpandProperty FullName)"

Write-Host "[5/6] Creating ZIP..."
Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zipArchive = [System.IO.Compression.ZipFile]::Open($zip, [System.IO.Compression.ZipArchiveMode]::Create)
try {
    Get-ChildItem -LiteralPath $staging -Recurse -File | ForEach-Object {
        $relative = $_.FullName.Substring($staging.Length + 1).Replace("\", "/")
        [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile(
            $zipArchive,
            $_.FullName,
            $relative,
            [System.IO.Compression.CompressionLevel]::Optimal
        ) | Out-Null
    }
} finally {
    $zipArchive.Dispose()
}
Assert-Path (Test-Path -LiteralPath $zip) "The ZIP was not created."

$archive = [System.IO.Compression.ZipFile]::OpenRead($zip)
try {
    $entries = @($archive.Entries | ForEach-Object { $_.FullName })
} finally {
    $archive.Dispose()
}
foreach ($entry in @(
    "ChromeExtension/manifest.json",
    "ChromeExtension/game.html",
    "LANServer/server.bundle.mjs",
    "LANServer/Start-LAN-Server.ps1",
    "LANServer/web/game.html",
    "README.txt"
)) {
    Assert-Path ($entries -contains $entry) "ZIP is missing: $entry"
}
$badEntries = $entries | Where-Object {
    $_ -match '(^|/)(node_modules|tests|artifacts|release|src|server/src)/' -or
    $_ -match '\.(sqlite|sqlite-wal|sqlite-shm|log|env)$' -or
    $_ -match '(^|/)\.env' -or
    $_ -match '(^|/)BDF'
}
Assert-Path (-not $badEntries) "ZIP contains a forbidden entry: $($badEntries | Select-Object -First 1)"

Write-Host "[6/6] Extracting to a fresh folder and smoke-checking the server..."
$verify = Join-Path $release ("verify-" + [guid]::NewGuid().ToString("N"))
Expand-Archive -LiteralPath $zip -DestinationPath $verify
try {
    $verifyExt = Join-Path $verify "ChromeExtension"
    $verifyLan = Join-Path $verify "LANServer"
    Assert-Path (Test-Path -LiteralPath (Join-Path $verifyExt "manifest.json")) "Extracted extension manifest is misplaced."
    Assert-Path (Test-Path -LiteralPath (Join-Path $verifyLan "web\game.html")) "Extracted server web build is missing."
    $verifyManifest = Get-Content -LiteralPath (Join-Path $verifyExt "manifest.json") -Raw -Encoding UTF8 | ConvertFrom-Json
    Assert-Path ($verifyManifest.action.default_popup -eq "popup.html") "Extracted manifest popup is wrong."
    Assert-Path (Test-Path -LiteralPath (Join-Path $verifyExt $verifyManifest.action.default_popup)) "Extracted popup file is missing."
    foreach ($icon in $verifyManifest.icons.PSObject.Properties) {
        Assert-Path (Test-Path -LiteralPath (Join-Path $verifyExt $icon.Value)) "Extracted icon is missing: $($icon.Value)"
    }

    $port = Free-Port
    $serverProcess = Start-Process -FilePath $node.Source -ArgumentList @(
        "server.bundle.mjs", "--port", "$port", "--host", "127.0.0.1"
    ) -WorkingDirectory $verifyLan -PassThru -WindowStyle Hidden
    try {
        $health = $null
        for ($attempt = 0; $attempt -lt 60; $attempt += 1) {
            Start-Sleep -Milliseconds 200
            if ($serverProcess.HasExited) { break }
            try {
                $health = Invoke-RestMethod -Uri "http://127.0.0.1:$port/api/health" -TimeoutSec 1
                if ($health.ok) { break }
            } catch {
                $health = $null
            }
        }
        Assert-Path ($null -ne $health -and $health.ok) "Extracted server did not answer /api/health."
        $page = Invoke-WebRequest -Uri "http://127.0.0.1:$port/play" -UseBasicParsing -TimeoutSec 3
        Assert-Path ($page.StatusCode -eq 200) "Extracted server did not serve the game page."
        Assert-Path ($page.Content -match "RoadRush") "Extracted game page content is unexpected."
        $board = Invoke-RestMethod -Uri "http://127.0.0.1:$port/api/leaderboard" -TimeoutSec 3
        Assert-Path ($board.fastest.Count -eq 0) "Fresh release database should start empty."
    } finally {
        if (-not $serverProcess.HasExited) {
            Stop-Process -Id $serverProcess.Id -Force
            Wait-Process -Id $serverProcess.Id -ErrorAction SilentlyContinue
        }
    }
} finally {
    for ($attempt = 0; $attempt -lt 5; $attempt += 1) {
        try {
            Remove-Item -LiteralPath $verify -Recurse -Force -ErrorAction Stop
            break
        } catch {
            Start-Sleep -Milliseconds 300
        }
    }
}

$size = (Get-Item -LiteralPath $zip).Length
Write-Host ""
Write-Host "Release created: $zip"
Write-Host ("Size: {0:N1} KB" -f ($size / 1KB))
Write-Host "Staging folder left for inspection: $staging"
Write-Host "Structural checks and extracted-server health check passed."
